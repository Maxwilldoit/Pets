export const TRANSLATIONS = Object.freeze(Object.fromEntries(SUPPORTED_LANGUAGES.map((locale, index) => [
  locale, Object.freeze(Object.fromEntries(Object.entries(messages).map(([key, values]) => [key, values[index]]))),
])));

export function createTranslator(locale) {
  const dictionary = TRANSLATIONS[resolveLanguage(locale)];
  return (key, params = {}) => (dictionary[key] ?? TRANSLATIONS.en[key] ?? key).replace(/\{(\w+)\}/g, (match, name) => (
    Object.hasOwn(params, name) ? String(params[name]) : match
  ));
}

