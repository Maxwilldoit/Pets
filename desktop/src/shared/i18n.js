export function localizeDiagnostic(message, locale) {
  const text = String(message ?? '');
  if (resolveLanguage(locale) !== 'en') return text;
  const nested = text.match(/^动画「(.*)」加载失败：(.*)$/s);
  if (nested) return `Could not load animation "${nested[1]}": ${localizeDiagnostic(nested[2], locale)}`;
  for (const [pattern, replacement] of diagnostics) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return text;
}
