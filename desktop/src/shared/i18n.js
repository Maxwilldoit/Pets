export const SUPPORTED_LANGUAGES = Object.freeze(['zh-CN', 'en']);

/** Resolve a stored preference without depending on Electron or browser globals. */
export function resolveLanguage(preference = 'auto', systemLocale = 'en') {
  const locale = SUPPORTED_LANGUAGES.includes(preference) ? preference : systemLocale;
  return /^zh(?:[-_]|$)/i.test(String(locale ?? '')) ? 'zh-CN' : 'en';
}

